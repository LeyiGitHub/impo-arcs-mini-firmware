"""Writes the hardware gallery in README.md from hardware/boards.json.

usage:
  hardware/render.py            rewrite the gallery between the README markers
  hardware/render.py --check    exit 1 if the gallery is stale or an image is missing
  hardware/render.py --images DIR
                                make hardware/images/<id>.webp (400 px tall) from
                                full-size <id>.webp cut-outs in DIR, then rewrite
"""
import argparse
import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "hardware/boards.json"
README = ROOT / "README.md"
IMAGES = ROOT / "hardware/images"
START = "<!-- hardware:start: generated by hardware/render.py from hardware/boards.json -->"
END = "<!-- hardware:end -->"
COLUMNS = 4
HEIGHT = 400


def load():
    return json.loads(CATALOG.read_text())


def install(board):
    if board["sdk"] == "linux":
        return "linux/install.sh"
    if board["sdk"] == "arcs":
        return "arcs/build.sh"
    return f"flash.sh {board['flash']}"


def cell(board):
    e = html.escape
    tags = " · ".join(board["highlights"])
    status = "<br><sub><i>Experimental</i></sub>" if board["status"] == "experimental" else ""
    return (
        f'<td align="center" valign="top" width="{100 // COLUMNS}%">'
        f'<a href="{e(board["link"])}"><img src="hardware/images/{board["id"]}.webp" height="150" alt="{e(board["vendor"])} {e(board["name"])}"></a><br>'
        f'<b>{e(board["name"])}</b><br>'
        f'<sub>{e(board["vendor"])} · {e(board["chip"])}</sub><br>'
        f"<sub>{e(tags)}</sub>{status}<br>"
        f"<code>{e(install(board))}</code>"
        "</td>"
    )


def gallery(catalog):
    boards = catalog["boards"]
    ready = sum(b["status"] == "ready" for b in boards)
    out = [START, ""]
    for category in catalog["categories"]:
        group = [b for b in boards if b["category"] == category["id"]]
        if not group:
            continue
        out += [f"### {category['title']}", "", "<table>"]
        for i in range(0, len(group), COLUMNS):
            row = group[i:i + COLUMNS]
            pad = "<td></td>" * (COLUMNS - len(row))
            out.append("<tr>" + "".join(cell(b) for b in row) + pad + "</tr>")
        out += ["</table>", ""]
    notes = [b for b in boards if b.get("note")]
    if notes:
        out += ["Before you flash:", ""]
        out += [f"- **{b['vendor']} {b['name']}**: {b['note']}" for b in notes]
        out.append("")
    out += [
        f"{len(boards)} boards: {ready} ready, {len(boards) - ready} experimental. "
        "Specifications, pins and per-board notes are in "
        "[`esp32/devices/README.md`](esp32/devices/README.md). More devices we are "
        "looking at are on [impo.ai/hardware](https://impo.ai/hardware/).",
        "",
        END,
    ]
    return "\n".join(out)


def render(text, catalog):
    if START not in text or END not in text:
        sys.exit(f"{README} has no hardware markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + gallery(catalog) + tail


def make_images(source, catalog):
    from PIL import Image

    IMAGES.mkdir(parents=True, exist_ok=True)
    for board in catalog["boards"]:
        src = Path(source) / f"{board['id']}.webp"
        if not src.exists():
            continue
        image = Image.open(src).convert("RGBA")
        box = image.getbbox()
        if box:
            image = image.crop(box)
        if image.height > HEIGHT:
            image = image.resize((round(image.width * HEIGHT / image.height), HEIGHT), Image.LANCZOS)
        image.save(IMAGES / f"{board['id']}.webp", "WEBP", quality=88, method=6)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--images")
    args = parser.parse_args()
    catalog = load()
    if args.images:
        make_images(args.images, catalog)
    missing = [b["id"] for b in catalog["boards"] if not (IMAGES / f"{b['id']}.webp").exists()]
    text = README.read_text()
    new = render(text, catalog)
    if args.check:
        problems = []
        if missing:
            problems.append("missing images: " + ", ".join(missing))
        if new != text:
            problems.append("README.md hardware gallery is stale: run hardware/render.py")
        if problems:
            sys.exit("\n".join(problems))
        return
    if missing:
        sys.exit("missing images: " + ", ".join(missing))
    README.write_text(new)


if __name__ == "__main__":
    main()
